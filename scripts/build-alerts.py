#!/usr/bin/env python3
"""Combine the SEO, news and cache-bus alert rules into one file for the miniKube repository (docs/seo/alerts-for-minikube-repo.yaml).

Sources (edit these, never the output):
  services/www/docs/seo/prometheus-alerts.yml   groups jithendar-com-seo, jithendar-com-seo-agent, jithendar-com-seo-ml
  services/www/docs/news/prometheus-alerts.yml  group  jithendar-com-news
  services/www/docs/cache-bus/prometheus-alerts.yml  group  jithendar-com-cache-bus

  python3 scripts/build-alerts.py           # (re)write the combined file
  python3 scripts/build-alerts.py --check   # CI: fail if the committed file is stale or a rule is malformed

Structural checks (always): unique group names, unique alert names, every rule has alert + expr + labels.severity +
annotations.summary, `for` is a duration. Full PromQL validation is `promtool check rules <file>` (CI runs it from the
pinned prom/prometheus image; locally when promtool is on PATH). This repository never applies the rules: a person
copies the file into the miniKube repo (docs/seo/OPERATIONS.md#alerts, "Alerts handoff").
"""

from __future__ import annotations

import re
import shutil
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "services/www/docs"
SOURCES = [DOCS / "seo/prometheus-alerts.yml", DOCS / "news/prometheus-alerts.yml", DOCS / "cache-bus/prometheus-alerts.yml"]
OUT = DOCS / "seo/alerts-for-minikube-repo.yaml"
DURATION = re.compile(r"^\d+(ms|s|m|h|d|w|y)$")

HEADER = """# GENERATED by scripts/build-alerts.py from services/www/docs/seo/prometheus-alerts.yml,
# services/www/docs/news/prometheus-alerts.yml and services/www/docs/cache-bus/prometheus-alerts.yml.
# Do not edit by hand: edit a source, then run the script.
#
# Handoff to the miniKube repository (this repository never applies alert rules, decision D-12):
#   1. In the miniKube repo, open deploy/minikube/observability/prometheus/files/alerts.yml.
#   2. Replace the groups named below (or append them the first time) with the groups in this file.
#   3. `promtool check rules alerts.yml` there, commit, and let its Prometheus reload.
#
# Groups: {groups}
"""


def load() -> list[dict]:
    groups: list[dict] = []
    for src in SOURCES:
        doc = yaml.safe_load(src.read_text())
        groups.extend(doc["groups"])
    return groups


def check(groups: list[dict]) -> list[str]:
    errs: list[str] = []
    names = [g["name"] for g in groups]
    if len(names) != len(set(names)):
        errs.append(f"duplicate group names: {names}")
    seen: set[str] = set()
    for g in groups:
        for r in g.get("rules") or []:
            a = r.get("alert")
            if not a:
                errs.append(f"{g['name']}: rule without alert name")
                continue
            if a in seen:
                errs.append(f"duplicate alert {a}")
            seen.add(a)
            if not str(r.get("expr", "")).strip():
                errs.append(f"{a}: empty expr")
            if (r.get("labels") or {}).get("severity") not in ("info", "warning", "critical"):
                errs.append(f"{a}: labels.severity must be info|warning|critical")
            if not (r.get("annotations") or {}).get("summary"):
                errs.append(f"{a}: annotations.summary missing")
            if "for" in r and not DURATION.match(str(r["for"])):
                errs.append(f"{a}: bad 'for' duration {r['for']!r}")
    return errs


def render(groups: list[dict]) -> str:
    body = yaml.safe_dump({"groups": groups}, sort_keys=False, allow_unicode=True, width=200)
    return HEADER.format(groups=", ".join(g["name"] for g in groups)) + body


def main(argv: list[str]) -> int:
    groups = load()
    errs = check(groups)
    if errs:
        print("\n".join(errs), file=sys.stderr)
        return 1
    text = render(groups)
    n = sum(len(g.get("rules") or []) for g in groups)
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is stale: run python3 scripts/build-alerts.py", file=sys.stderr)
            return 1
        print(f"{OUT.relative_to(ROOT)} is up to date ({len(groups)} groups, {n} rules)")
    else:
        OUT.write_text(text)
        print(f"wrote {OUT.relative_to(ROOT)} ({len(groups)} groups, {n} rules)")
    promtool = shutil.which("promtool")
    if promtool:
        return subprocess.run([promtool, "check", "rules", str(OUT)], check=False).returncode  # noqa: S603
    print("promtool not on PATH: structural checks only (CI runs promtool)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
